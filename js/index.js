    document.getElementById("mealDescription").textContent = meal.description;
    document.getElementById("rating").textContent = meal.rating;
    document.getElementById("reviews").textContent = meal.reviews;
    document.getElementById("difficulty").textContent = meal.difficulty;
    document.getElementById("cuisine").textContent = meal.cuisine;
    document.getElementById("prepTime").textContent = meal.prepTime;
    document.getElementById("cookTime").textContent = meal.cookTime;
    document.getElementById("servings").textContent = meal.servings;


    var prepAlert = document.getElementById("prepAlert");
    var prepMinutes = parseInt(meal.prepTime);
